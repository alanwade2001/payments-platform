CREATE TABLE initiation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         BIGINT NOT NULL,
    message_id          VARCHAR(35) NOT NULL,
    source_created_at   TIMESTAMPTZ NOT NULL,
    received_at         TIMESTAMPTZ NOT NULL,
    status              varchar(20) not null,

    CONSTRAINT uk_initiation_message_id
        UNIQUE (message_id)
);

CREATE TABLE payment (
     id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     initiation_id               BIGINT NOT NULL,
     payment_information_id      VARCHAR(35) NOT NULL,
     debtor_name                 VARCHAR(140) NOT NULL,
     debtor_iban                 VARCHAR(34) NOT NULL,
     requested_execution_date    DATE NOT NULL,

     pmt_inf                     JSONB NOT NULL,

     CONSTRAINT fk_payment_initiation
         FOREIGN KEY (initiation_id)
             REFERENCES initiation (id)
             ON DELETE CASCADE,

     CONSTRAINT uk_payment_initiation_payment_information
         UNIQUE (initiation_id, payment_information_id)
);


CREATE TABLE payment_transaction (
     id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     payment_id          BIGINT NOT NULL,
     end_to_end_id       VARCHAR(35) NOT NULL,
     amount              NUMERIC(18, 2) NOT NULL,
     currency            VARCHAR(3) NOT NULL,
     creditor_name       VARCHAR(140) NOT NULL,
     creditor_iban       VARCHAR(34) NOT NULL,

     cdt_trf_tx_inf      JSONB NOT NULL,

     CONSTRAINT fk_payment_transaction_payment
         FOREIGN KEY (payment_id)
             REFERENCES payment (id)
             ON DELETE CASCADE
);
CREATE INDEX idx_payment_initiation_id
    ON payment (initiation_id);

CREATE INDEX idx_payment_transaction_payment_id
    ON payment_transaction (payment_id);